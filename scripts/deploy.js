const fs = require("fs");
const path = require("path");
const hre = require("hardhat");

const RPC = {
  localhost: "http://127.0.0.1:8545",
  amoy: "https://rpc-amoy.polygon.technology",
};

async function main() {
  const [deployer] = await hre.ethers.getSigners();
  console.log("Deploying with:", deployer.address);

  const trace = await (await hre.ethers.getContractFactory("AyurTrace")).deploy();
  await trace.waitForDeployment();
  const address = await trace.getAddress();
  const { chainId } = await hre.ethers.provider.getNetwork();
  console.log("AyurTrace deployed to:", address, "(chainId", chainId.toString() + ")");

  // Save deployment info for scripts + frontend
  const dir = path.join(__dirname, "..", "deployments");
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(
    path.join(dir, `${hre.network.name}.json`),
    JSON.stringify({ address, chainId: Number(chainId), admin: deployer.address }, null, 2)
  );

  const config = `// Auto-generated by scripts/deploy.js - do not edit by hand
window.AYUR_CONFIG = {
  contractAddress: "${address}",
  chainId: ${Number(chainId)},
  rpcUrl: "${RPC[hre.network.name] || ""}",
  networkName: "${hre.network.name}",
};
`;
  fs.writeFileSync(path.join(__dirname, "..", "frontend", "config.js"), config);
  console.log("Wrote frontend/config.js and deployments/" + hre.network.name + ".json");
}

main().catch((e) => {
  console.error(e);
  process.exitCode = 1;
});
